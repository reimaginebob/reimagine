// Generates src/data/user-guide-content.js. Gitignored and rebuilt every
// prebuild; never committed.
//
// Order comes from src/data/user-guide/ORDER.json, not from a readdir().sort().
// It used to be the sort: filenames carried numeric prefixes (04-orientation-phase.md),
// so alphabetical order and reading order happened to agree. They stopped agreeing
// the moment filenames became stable slugs — a sorted readdir would have handed the
// Coach the guide in alphabetical order (add-an-opportunity, before-you-begin,
// faq-and-troubleshooting, ...), which reads as a shuffled manual and puts the
// contents page in the middle. chapterFiles() is the same source the PDF builder,
// the contents page, and the staleness hash read, so all four cannot disagree.
//
// Two exports, two different jobs:
//
// USER_GUIDE_CONTENT — the whole guide as one string (index.md leads, then
// the chapters in reading order), unchanged from before 2026-09-06. Two
// consumers still need the whole thing, unnarrowed: api/claude.js reads it
// as the register/voice reference for generation prompts (not topical
// grounding — it needs the guide's writing style regardless of which
// prompt is running), and api/coach.js falls back to it for currentStep
// values step-aware gating doesn't narrow (src/data/guide-step-relevance.js
// FALLBACK_STEPS, or any step with no explicit mapping there).
//
// USER_GUIDE_UNITS — the same source content, keyed instead of joined, for
// api/coach.js's step-aware gating. Most keys are a whole chapter's
// filename (e.g. 'add-an-opportunity.md'). focus-playbook.md is the
// exception: at 55K it's the largest chapter in the guide and documents
// eleven different Focus Playbook sections, so it's split into named units
// keyed 'focus-playbook:<unit>' (scripts/lib/split-focus-playbook.mjs) —
// see that file and src/data/guide-step-relevance.js for the reasoning.
// index.md is deliberately absent from USER_GUIDE_UNITS: it's the guide's
// own table of contents, meant for a human browsing chapter by chapter, not
// grounding Coach needs for any step.
import fs from 'node:fs'
import path from 'node:path'
import { CHAPTERS_DIR, INDEX_FILE, chapterFiles } from './lib/user-guide-order.mjs'
import { splitFocusPlaybook, FOCUS_PLAYBOOK_UNIT_ORDER } from './lib/split-focus-playbook.mjs'

const OUT_FILE = path.join(process.cwd(), 'src/data/user-guide-content.js')

const files = [INDEX_FILE, ...chapterFiles()]

const readChapter = f => `# ${f}\n\n${fs.readFileSync(path.join(CHAPTERS_DIR, f), 'utf-8')}`

const content = files.map(readChapter).join('\n\n---\n\n')

const units = {}
for (const f of chapterFiles()) {
  if (f === 'focus-playbook.md') {
    const split = splitFocusPlaybook(fs.readFileSync(path.join(CHAPTERS_DIR, f), 'utf-8'))
    for (const key of FOCUS_PLAYBOOK_UNIT_ORDER) units[`focus-playbook:${key}`] = split[key]
  } else {
    units[f] = readChapter(f)
  }
}

const escapedContent = JSON.stringify(content)
const escapedUnits = JSON.stringify(units, null, 2)

fs.writeFileSync(
  OUT_FILE,
  `// Auto-generated by scripts/build-user-guide.mjs. Do not edit by hand.\nexport const USER_GUIDE_CONTENT = ${escapedContent}\nexport const USER_GUIDE_UNITS = ${escapedUnits}\n`,
)

console.log(`Wrote ${content.length} chars from ${files.length} files (USER_GUIDE_CONTENT) and ${Object.keys(units).length} units (USER_GUIDE_UNITS) to ${OUT_FILE}`)
