// Generates src/data/user-guide-content.js — the whole user guide as one string,
// injected verbatim into My Coach (api/coach.js). Gitignored and rebuilt every
// prebuild; never committed.
//
// Order comes from src/data/user-guide/ORDER.json, not from a readdir().sort().
// It used to be the sort: filenames carried numeric prefixes (04-orientation-phase.md),
// so alphabetical order and reading order happened to agree. They stopped agreeing
// the moment filenames became stable slugs — a sorted readdir would have handed the
// Coach the guide in alphabetical order (add-an-opportunity, before-you-begin,
// faq-and-troubleshooting, ...), which reads as a shuffled manual and puts the
// contents page in the middle. chapterFiles() is the same source the PDF builder,
// the contents page, and the staleness hash read, so all four cannot disagree.
//
// index.md (the contents page) leads, then the chapters in reading order.
import fs from 'node:fs'
import path from 'node:path'
import { CHAPTERS_DIR, INDEX_FILE, chapterFiles } from './lib/user-guide-order.mjs'

const OUT_FILE = path.join(process.cwd(), 'src/data/user-guide-content.js')

const files = [INDEX_FILE, ...chapterFiles()]

const content = files
  .map(f => `# ${f}\n\n${fs.readFileSync(path.join(CHAPTERS_DIR, f), 'utf-8')}`)
  .join('\n\n---\n\n')

const escaped = JSON.stringify(content)

fs.writeFileSync(
  OUT_FILE,
  `// Auto-generated by scripts/build-user-guide.mjs. Do not edit by hand.\nexport const USER_GUIDE_CONTENT = ${escaped}\n`,
)

console.log(`Wrote ${content.length} chars from ${files.length} files to ${OUT_FILE}`)
